// Writes the clip metadata for tools that do not read the .glb:
//   exports/clips.json             markers, durations, root motion, priorities
//   exports/RoundPlumberClips.luau the same data as a Luau ModuleScript
import fs from 'node:fs';
import path from 'node:path';

const lua = (v, indent = '') => {
	if (v === null || v === undefined) return 'nil';
	if (typeof v === 'number') return Number.isInteger(v) ? String(v) : String(+v.toFixed(4));
	if (typeof v === 'boolean') return String(v);
	if (typeof v === 'string') return JSON.stringify(v);
	if (Array.isArray(v)) {
		if (v.every((x) => typeof x === 'number')) return `{ ${v.map((x) => lua(x)).join(', ')} }`;
		return `{\n${v.map((x) => `${indent}\t${lua(x, indent + '\t')},`).join('\n')}\n${indent}}`;
	}
	const keys = Object.keys(v).filter((k) => v[k] !== null && v[k] !== undefined);
	return `{\n${keys.map((k) => `${indent}\t${/^[A-Za-z_]\w*$/.test(k) ? k : `[${JSON.stringify(k)}]`} = ${lua(v[k], indent + '\t')},`).join('\n')}\n${indent}}`;
};

export function writeClipData(info, root) {
	fs.writeFileSync(path.join(root, 'exports/clips.json'), JSON.stringify(info, null, 2) + '\n');
	const byName = {};
	for (const c of info) {
		byName[c.name] = {
			group: c.group, variant: c.variant, duration: c.duration, looped: c.loop, priority: c.priority,
			faceOnly: c.faceOnly || null, label: c.label,
			markers: c.markers.map((m) => ({ name: m.name, time: m.time })),
			rootMotion: c.rootMotion,
		};
	}
	const groups = {};
	for (const c of info) (groups[c.group] ??= []).push(c.name);
	const src = `--!strict
-- GENERATED by tools/round-plumber/build.js - do not edit by hand.
-- Clip timing data (durations, priorities, KeyframeMarker times, root motion):
-- marker times are identical for every variant of a group, so hitboxes,
-- i-frames and damage never depend on which variant was picked.
local Clips = {}

Clips.FPS = 30

Clips.Clips = ${lua(byName)}

-- group -> variant clip names
Clips.Groups = ${lua(groups)}

return Clips
`;
	fs.writeFileSync(path.join(root, 'exports/RoundPlumberClips.luau'), src);
}
